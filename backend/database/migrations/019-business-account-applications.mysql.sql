CREATE TABLE business_account_applications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 account_id BIGINT UNSIGNED NOT NULL,
 application_type VARCHAR(24) NOT NULL,
 business_id BIGINT UNSIGNED NULL,
 destination_id BIGINT UNSIGNED NOT NULL,
 category_code VARCHAR(40) NOT NULL,
 business_name VARCHAR(180) NOT NULL,
 relationship_code VARCHAR(32) NOT NULL,
 contact_phone VARCHAR(40) NOT NULL DEFAULT '',
 message VARCHAR(1000) NOT NULL DEFAULT '',
 consent_version VARCHAR(40) NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'pending',
 admin_note VARCHAR(1000) NOT NULL DEFAULT '',
 reviewed_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX business_account_app_queue (status,created_at),
 INDEX business_account_app_account (account_id,status),
 INDEX business_account_app_business (business_id,status),
 CONSTRAINT business_account_app_account_fk FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE,
 CONSTRAINT business_account_app_business_fk FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE SET NULL,
 CONSTRAINT business_account_app_destination_fk FOREIGN KEY (destination_id) REFERENCES destinations(id) ON DELETE RESTRICT,
 CONSTRAINT business_account_app_category_fk FOREIGN KEY (category_code) REFERENCES service_categories(code) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
