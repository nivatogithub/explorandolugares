CREATE TABLE business_research_contacts (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 business_id BIGINT UNSIGNED NOT NULL,
 channel VARCHAR(24) NOT NULL,
 contact_value VARCHAR(500) NOT NULL,
 source_url VARCHAR(1000) NOT NULL,
 source_type VARCHAR(80) NOT NULL DEFAULT '',
 source_field VARCHAR(80) NOT NULL DEFAULT '',
 source_period VARCHAR(120) NOT NULL DEFAULT '',
 consulted_at DATE NOT NULL,
 evidence_status VARCHAR(100) NOT NULL,
 source_note TEXT NOT NULL,
 authorization_status VARCHAR(80) NOT NULL DEFAULT 'NO_OBTENIDA',
 legal_basis_status VARCHAR(500) NOT NULL,
 crm_stage VARCHAR(80) NOT NULL DEFAULT '',
 potential_subscription VARCHAR(40) NOT NULL DEFAULT '',
 marketing_consent TINYINT(1) NOT NULL DEFAULT 0,
 campaign_allowed TINYINT(1) NOT NULL DEFAULT 0,
 suppressed TINYINT(1) NOT NULL DEFAULT 0,
 record_hash CHAR(64) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY business_research_observation (business_id,record_hash),
 INDEX business_research_business (business_id,channel),
 CONSTRAINT business_research_business_fk FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
