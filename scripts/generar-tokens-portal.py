#!/usr/bin/env python3
"""Generate namespaced portal tokens without overriding the legacy shared stylesheet."""
import json,argparse
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def render():
 data=json.loads((ROOT/'design/portal/tokens.json').read_text());lines=['/* Generated by scripts/generar-tokens-portal.py; edit design/portal/tokens.json. */',':root {']
 for group,prefix in [('colors',''),('radii','radius-'),('fonts','font-')]:
  for key,value in data[group].items():lines.append(f'  --el-{prefix}{key}: {value};')
 return '\n'.join(lines+['}',''])
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();path=ROOT/'backend/public/assets/cobertura/portal-tokens.css';expected=render()
 if args.check:
  if not path.exists() or path.read_text()!=expected:raise SystemExit('Portal tokens are out of date')
  print('Portal tokens: OK')
 else:path.write_text(expected)
